//! Projections generated from `keys::KEYS`: `schema.json`, `defaults.toml`, `defaults.json`.
//! `generate --check` fails (`drift`) when an on-disk file differs from the generated text.

use std::path::Path;

use serde_json::{json, Map, Value};

use super::keys::{Kind, KEYS};
use super::resolve::{defaults_flat, nest};
use super::{ConfigError, Result};

const MARKER: &str = "GENERATED by `oats-meetings-rs config generate` from crates/core/src/config/keys.rs; do not edit";

/// Rebuild every object with sorted keys. Cargo feature unification can turn on serde_json's
/// `preserve_order` (gpui does), so output order must not depend on the map implementation.
fn sorted(v: &Value) -> Value {
    match v {
        Value::Object(m) => {
            let mut keys: Vec<&String> = m.keys().collect();
            keys.sort();
            let mut out = Map::new();
            for k in keys {
                out.insert(k.clone(), sorted(&m[k]));
            }
            Value::Object(out)
        }
        other => other.clone(),
    }
}

pub fn defaults_json() -> String {
    let mut s = serde_json::to_string_pretty(&sorted(&nest(&defaults_flat()))).expect("serializable");
    s.push('\n');
    s
}

fn toml_lit(v: &Value) -> String {
    match v {
        Value::Bool(b) => b.to_string(),
        Value::String(s) => format!("{s:?}"),
        other => other.to_string(),
    }
}

pub fn defaults_toml() -> String {
    let mut out = format!("# {MARKER}\n");
    let mut last_table = String::new();
    for k in sorted_keys() {
        let (table, leaf) = k.path.rsplit_once('.').expect("keys are dotted");
        if table != last_table {
            out.push_str(&format!("\n[{table}]\n"));
            last_table = table.to_string();
        }
        out.push_str(&format!("# {}\n{leaf} = {}\n", k.doc, toml_lit(&k.default.to_json())));
    }
    out
}

fn sorted_keys() -> Vec<&'static super::keys::Key> {
    let mut ks: Vec<_> = KEYS.iter().collect();
    ks.sort_by_key(|k| k.path);
    ks
}

pub fn schema_json() -> String {
    let mut root = Map::new();
    root.insert("$schema".into(), json!("http://json-schema.org/draft-07/schema#"));
    root.insert("$comment".into(), json!(MARKER));
    root.insert("title".into(), json!("oats-meetings-rs config"));
    root.insert("type".into(), json!("object"));
    root.insert("additionalProperties".into(), json!(false));
    root.insert("properties".into(), Value::Object(Map::new()));
    for k in sorted_keys() {
        let mut leaf = Map::new();
        match k.kind {
            Kind::Bool => {
                leaf.insert("type".into(), json!("boolean"));
            }
            Kind::Str => {
                leaf.insert("type".into(), json!("string"));
            }
            Kind::Enum(vs) => {
                leaf.insert("type".into(), json!("string"));
                leaf.insert("enum".into(), json!(vs));
            }
        }
        leaf.insert("default".into(), k.default.to_json());
        leaf.insert("description".into(), json!(k.doc));
        leaf.insert("x-ui".into(), json!(k.ui));
        let mut cur = root
            .get_mut("properties")
            .and_then(Value::as_object_mut)
            .expect("properties object");
        let parts: Vec<&str> = k.path.split('.').collect();
        for (i, part) in parts.iter().enumerate() {
            if i + 1 == parts.len() {
                cur.insert((*part).to_string(), Value::Object(leaf.clone()));
            } else {
                let node = cur.entry((*part).to_string()).or_insert_with(|| {
                    json!({"type": "object", "additionalProperties": false, "properties": {}})
                });
                cur = node
                    .get_mut("properties")
                    .and_then(Value::as_object_mut)
                    .expect("properties object");
            }
        }
    }
    let mut s = serde_json::to_string_pretty(&sorted(&Value::Object(root))).expect("serializable");
    s.push('\n');
    s
}

pub fn projections() -> Vec<(&'static str, String)> {
    vec![
        ("defaults.json", defaults_json()),
        ("defaults.toml", defaults_toml()),
        ("schema.json", schema_json()),
    ]
}

pub fn write(dir: &Path) -> Result<()> {
    std::fs::create_dir_all(dir)
        .map_err(|e| ConfigError::new("io_error", format!("{}: {e}", dir.display())))?;
    for (name, text) in projections() {
        let p = dir.join(name);
        std::fs::write(&p, text)
            .map_err(|e| ConfigError::new("io_error", format!("{}: {e}", p.display())))?;
    }
    Ok(())
}

/// Err(`drift`) naming every file that differs from the generated text or is missing.
pub fn check(dir: &Path) -> Result<()> {
    let mut bad = Vec::new();
    for (name, text) in projections() {
        match std::fs::read_to_string(dir.join(name)) {
            Ok(on_disk) if on_disk == text => {}
            Ok(_) => bad.push(format!("{name} (edited)")),
            Err(_) => bad.push(format!("{name} (missing)")),
        }
    }
    if bad.is_empty() {
        Ok(())
    } else {
        Err(ConfigError::new(
            "drift",
            format!(
                "generated files differ from keys.rs: {}; run `oats-meetings-rs config generate`",
                bad.join(", ")
            ),
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_config_dir() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../config")
    }

    #[test]
    fn committed_projections_are_current() {
        check(&repo_config_dir()).unwrap();
    }

    #[test]
    fn hand_edit_is_drift() {
        let d = tempfile::tempdir().unwrap();
        write(d.path()).unwrap();
        check(d.path()).unwrap();
        let p = d.path().join("schema.json");
        let mut s = std::fs::read_to_string(&p).unwrap();
        s.push_str(" \n");
        std::fs::write(&p, s).unwrap();
        let e = check(d.path()).unwrap_err();
        assert_eq!(e.code, "drift");
        assert!(e.message.contains("schema.json"));
    }

    #[test]
    fn missing_file_is_drift() {
        let d = tempfile::tempdir().unwrap();
        assert_eq!(check(d.path()).unwrap_err().code, "drift");
    }

    #[test]
    fn toml_projection_round_trips_to_defaults() {
        let tv: toml::Value = toml::from_str(&defaults_toml()).unwrap();
        let jv = serde_json::to_value(tv).unwrap();
        assert_eq!(jv, nest(&defaults_flat()));
    }

    #[test]
    fn projections_carry_the_generated_marker() {
        assert!(defaults_toml().contains("GENERATED"));
        assert!(schema_json().contains("GENERATED"));
    }
}
