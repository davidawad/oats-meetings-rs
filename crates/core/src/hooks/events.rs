/// Every event name, in table order.
pub fn names() -> Vec<&'static str> {
    TABLE.iter().map(|s| s.name).collect()
}

pub fn find(name: &str) -> Option<&'static Spec> {
    TABLE.iter().find(|s| s.name == name)
}

/// The hook events a published bus message stands for, in table order.
pub fn events_for(topic: &str, data: &Value) -> Vec<&'static Spec> {
    TABLE
        .iter()
        .filter(|s| s.topics.contains(&topic) && (s.when)(topic, data))
        .collect()
}

