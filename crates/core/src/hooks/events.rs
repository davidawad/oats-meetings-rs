//! The hook event contract (dot-4uzgol.111.2, docs/design/hooks.md L1): one table names every
//! hook event with its description, the bus topic(s) that produce it, the JSON Schema of its
//! `data`, how its dedup key is formed and an example. Everything else is read from it: the
//! `[[hooks]]` event check and `schema.json` enum, `hook-events`, `config/hook-events.json`,
//! the `hook-add` / `hook-edit` docs and the Settings event picker.
//!
//! A hook run gets one envelope, `oats.hook-event/1`, on stdin and in the file `OATS_EVENT_FILE`:
//! `{schema, event, seq, at, run_id, dedup, hook, session{id, dir, title, audio, transcript},
//! calendar{title, start, end, attendees, source} | null, data}`. `seq` counts the bus messages
//! of one session (monotonic within it); a hook fires at most once per `dedup` key.

use serde_json::{json, Map, Value};

/// The envelope's schema id, the `schema` field of every envelope.
pub const SCHEMA: &str = "oats.hook-event/1";

pub const MARKER: &str =
    "GENERATED by `oats-meetings-rs config generate` from crates/core/src/hooks/events.rs; do not edit";

/// One hook event.
pub struct Spec {
    pub name: &'static str,
    pub description: &'static str,
    /// The bus topics it follows; empty when an action fires it directly.
    pub topics: &'static [&'static str],
    /// Whether a message on one of `topics` stands for it.
    when: fn(&str, &Value) -> bool,
    /// How the dedup key is formed, for people.
    pub dedup: &'static str,
    /// The part of the dedup key after `<session>:<event>` from (topic, data, seq); empty for
    /// once per session.
    key: fn(&str, &Value, u64) -> String,
    /// The JSON Schema of `data`.
    data: fn() -> Value,
    /// A `data` that holds to it.
    example: fn() -> Value,
}

impl Spec {
    pub fn data_schema(&self) -> Value {
        (self.data)()
    }

    pub fn example_data(&self) -> Value {
        (self.example)()
    }

    /// The dedup key of this event for `session` from a message (`topic` "" when fired directly).
    pub fn dedup_key(&self, session: &str, topic: &str, data: &Value, seq: u64) -> String {
        let k = (self.key)(topic, data, seq);
        if k.is_empty() {
            format!("{session}:{}", self.name)
        } else {
            format!("{session}:{}:{k}", self.name)
        }
    }
}

fn always(_: &str, _: &Value) -> bool {
    true
}

fn never(_: &str, _: &Value) -> bool {
    false
}

fn once(_: &str, _: &Value, _: u64) -> String {
    String::new()
}

fn each(_: &str, _: &Value, seq: u64) -> String {
    seq.to_string()
}

fn matched(_: &str, d: &Value) -> bool {
    d["calendar"]["event"].is_object()
}

fn s() -> Value {
    json!({"type": "string"})
}

fn s_or_null() -> Value {
    json!({"type": ["string", "null"]})
}

fn int() -> Value {
    json!({"type": "integer"})
}

fn int_or_null() -> Value {
    json!({"type": ["integer", "null"]})
}

/// An object schema; extra properties are allowed (a payload may grow), the listed ones are typed.
fn obj(required: &[&str], props: Value) -> Value {
    json!({"type": "object", "required": required, "properties": props})
}

/// What `recording-started` carries (the `record-start` answer).
fn start_props() -> Value {
    json!({
        "session": s(), "path": s(), "backend": s(), "system_backend": s_or_null(),
        "channels": int(), "rate": int(), "started_at": s(), "title": s(),
        "transcription": {"type": ["object", "null"]},
        "calendar": {"type": "object"},
        "auto_start": {"type": "object"},
    })
}

/// What `recording-stopped` carries (the `record-stop` answer).
fn stop_props() -> Value {
    json!({
        "session": s(), "path": s(), "duration_ms": int(), "trimmed_ms": int_or_null(),
        "by": s(), "forced": {"type": "boolean"}, "reason": s_or_null(),
        "transcription": {"type": ["object", "null"]}, "calendar": {"type": "object"},
        "error": s(),
    })
}

